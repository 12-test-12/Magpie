-- =============================================================================
--  013_kind_fingerprint.sql —— 离线指纹引擎（4.3）的两件登记事：
--
--    1. `product` / `service` 的产出者追加 `fingerprint@1`（`json_insert`）；
--    2. `fingerprint` 观测字段声明为多值（同一服务上多条规则各自命中）。
--
--  与 004–012 同一条纪律：**只增不改**（红线 R4）。已应用的迁移被改动
--  → 校验和不匹配 → `migrate()` 直接报错。所以这一份只做两条 INSERT/UPDATE，
--  不碰任何既有列、既有表、既有 CHECK。
--
--  ---------------------------------------------------------------------------
--  一、为什么指纹引擎的产出者**必须**是 `fingerprint@1` 这样一个解析器指纹
--  ---------------------------------------------------------------------------
--  4.2 的 `secret` 在这里登记的是**空** produced_by，理由写在 012 的文件头
--  第三节：它的产出者是一条管线阶段，不是一个解析器。4.3 走不到那条路上 ——
--  两个原因：
--
--    * 命中要写 `service --runs--> product`，而 `service` 的身份只能从
--      **响应所属的请求**（请求行 / Host / 绝对 URL）算出来。读格式、认领
--      文件、拿一份黄金夹具，这三件事就是"解析器"的定义 —— 指纹引擎必须是
--      一个真的解析器（`magpie/core/parsers/fingerprint.py`）；
--    * `verify_g3.py` 的 B 段对 produced_by 的每一项都要求"它是某个**已发现
--      的解析器**"（这一条不分新老 kind，指不到东西的声明是硬失败）。往
--      `product` 上追加一个阶段名会让 G3 当场红。
--
--  于是判据"按 004 的写法把新产出者追加进 produced_by"落到本步：
--
--    * 用 `json_insert` 而不是字符串拼接 —— 理由同 004 / 005 / 006 / 007 /
--      011：`produced_by` 是 canonical JSON 数组，拼接遇到坏数据会静默产出
--      畸形数组，而 json 函数让迁移当场回滚。`NOT EXISTS` 是幂等保险；
--    * **`service` 也要追加**，不只 `product`：引擎每次命中都先声明这段响应
--      属于哪个服务（`runs` 的主体），`service` 实体就是它产出的。004 追加
--      `nmap@1` 时同理覆盖了它产出的每一个 kind —— "只登记一半"会让
--      `magpie kinds` 的产出者一栏对 `service` 说假话。
--    * Python 侧镜像（`base.KIND_REGISTRY`）同步改，顺序与 `json_insert`
--      的追加一致（追加在末尾）—— `test_kind_registry_matches_the_python_
--      mirror` 断言两边逐字相等。
--
--  ---------------------------------------------------------------------------
--  二、为什么不新增 kind（"新 kind（若有）三件套"的"若有"这一半）
--  ---------------------------------------------------------------------------
--  命中的落点是 `product`（已登记，三件套早在 003 就齐了）+ `runs`（已登记
--  的关系动词）。"某台服务上跑着 nginx@1.24.0"不是一个新的事实类型 ——
--  nmap `-sV` 与 httpx `tech[]` 落的就是这同两样。凭空造一个 `fingerprint`
--  kind 会把同一个事实拆进两个互不相见的抽屉（计划书 §3.6 第 4 条：共享的
--  东西必须外提，而不是每来一个来源建一套）。所以本步**没有**三件套要做，
--  kind 总数维持 11。
--
--  ---------------------------------------------------------------------------
--  三、`fingerprint` 观测字段为什么是多值
--  ---------------------------------------------------------------------------
--  观测形状是 `service` 上的 `fingerprint` = `{product, rule, where, evidence}`。
--  同一个服务命中两条规则（nginx + PHP 是常态）→ 同实体同字段两个值 ——
--  `v_field_conflicts` 的口径是"同实体同字段多值即冲突"，不声明就会给每个
--  命中两条规则的服务开一条**假** Inbox 项。多个值在这里是"来源各自枚举
--  出来的枚举项"（各条规则的证据），正是 `010_multivalue_fields.sql` 文件头
--  那把尺子要收的形状。与 012 的 `location` 同一条纪律：声明表是白名单，
--  每一行都要带理由（下面的 `why`），`test_the_declaration_is_narrow` 比的是
--  **集合相等**。
-- =============================================================================

PRAGMA foreign_keys = ON;

-- -----------------------------------------------------------------------------
-- 1. 产出者追加：product 与 service 各多一个 fingerprint@1
-- -----------------------------------------------------------------------------

UPDATE kind_registry
   SET produced_by = json_insert(produced_by, '$[#]', 'fingerprint@1')
 WHERE kind IN ('product', 'service')
   AND NOT EXISTS (SELECT 1 FROM json_each(produced_by)
                    WHERE json_each.value = 'fingerprint@1')
   AND json_valid(produced_by);

-- -----------------------------------------------------------------------------
-- 2. fingerprint 观测字段：多值声明（白名单 + 理由）
-- -----------------------------------------------------------------------------

INSERT OR IGNORE INTO multivalue_fields
    (field_namespace, semantic_field, why)
VALUES
    ('observation_field', 'fingerprint',
     '同一 service 上多条规则各自命中 → 各自的证据 JSON; 声明多值避免假冲突');
