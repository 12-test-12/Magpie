-- =============================================================================
--  004_kind_cidr.sql —— 登记 `cidr`（网段）这个 kind（开发实施计划 3.1 · nmap）
--
--  为什么必须是**新增迁移**而不是改 003：红线 R4 —— 已应用的迁移文件被改动 →
--  校验和不匹配 → `migrate()` 直接报错（见 schema/003 的文件头与
--  `magpie/core/migrate.py`）。老库跑过 003 之后，`kind_registry` 就已经是
--  一份"当时被确认过的词表"；往它里面加一行是**新事实**，改旧文件是篡改历史。
--
--  ---------------------------------------------------------------------------
--  为什么这一步要加一个 kind
--  ---------------------------------------------------------------------------
--  3.1 之前没有任何来源产出网段，所以 "ip 与 cidr 是两个 kind" 这句话在 003 的
--  注释里只是**一句声明**（`ip` 的 identity_rule 里写着"网段是另一种 kind，
--  不在这里折叠"），而库里没有 cidr 这一行 —— 那时登记它等于凭空设计一套没有
--  产出者的约束（003 的种子注释把这条纪律说得很清楚：**下一个 kind 要进来，
--  同样必须带齐三件套**）。
--
--  nmap 的 `-oX` 是第一个真实的产出者：`<target specification="10.0.0.0/24">`
--  就是"这次扫描扫的是哪一段"。于是三件套在本步**同时**到位：
--
--    * 身份规则 —— `normalize.normalize_cidr`（主机位补齐：10.0.0.7/24 →
--      10.0.0.0/24，同一网段的两种写法是同一个实体）；
--    * 样例夹具 —— `fixtures/kinds/cidr.json`（可执行：样例真的被规则算成 key）；
--    * 镜头归属 —— `assets`（它是"手上有什么"的一部分，与服务镜头无关。
--      网段本身不跑任何东西，它只是地址的集合）。
--
--  ---------------------------------------------------------------------------
--  为什么不是把网段折进 `ip`
--  ---------------------------------------------------------------------------
--  `1.2.3.4` 与 `1.2.3.0/24` 折成同一个实体，会让「哪台机器」这个问题的答案
--  静默变成「哪一段」—— 003 里 `ip` 的 identity_rule 已经把这条写死了。反过来
--  也一样：网段有自己的用途（"哪些资产落在 DMZ 里"），而 IP 没有。
--
--  注意这次迁移**只做 INSERT，不动任何既有行**：`produced_by` 的更新（把
--  `nmap@1` 追加到 `ip` / `service` / `product` 三行上）也在这里做，理由是
--  词表的唯一事实来源就是这张表 —— Python 侧的镜像（`base.KIND_REGISTRY`）
--  与它逐行一致，测试断言两边分叉即红。
-- =============================================================================

PRAGMA foreign_keys = ON;

-- -----------------------------------------------------------------------------
-- 1. 新 kind：cidr
-- -----------------------------------------------------------------------------
--  identity_rule 的正文**必须与** `fixtures/kinds/cidr.json` 的 `identity_rule`
--  逐字一致（`test_every_registered_kind_has_all_three_parts` 断言这一点）——
--  两份描述一旦分叉，"哪个才是身份规则"就没有答案了。

INSERT INTO kind_registry
    (kind, identity_rule, fixture_path, lens, produced_by, registered_at)
VALUES
    ('cidr',
     '网段的规范写法（normalize.normalize_cidr）：网络地址 + 前缀长度，主机位补齐（10.0.0.7/24 → 10.0.0.0/24），IPv4-mapped IPv6 折成 IPv4。**网段与单个 IP 是两个 kind**，不互相折叠 —— 把 1.2.3.4 与 1.2.3.0/24 认成同一个实体，会让「哪台机器」的答案变成「哪一段」。',
     'fixtures/kinds/cidr.json', 'assets', '["nmap@1"]',
     strftime('%Y-%m-%dT%H:%M:%SZ','now'));

-- -----------------------------------------------------------------------------
-- 2. 既有 kind 的产出者补登
-- -----------------------------------------------------------------------------
--  3.1 之后，`domain` / `ip` / `service` / `product` 各自多了一个真实产出者
--  （`domain` 也在内：nmap 带 `-R` 反解主机名时会产出 `domain` 实体）。
--  这一列不是装饰：`test_every_registered_kind_has_a_real_producer` 会拿它去
--  **夹具里反查**这个 kind 是否真的出现过 —— 声明了却不产出的那一条会立刻红。
--
--  为什么用"读旧值 + 追加"而不是直接写一个常量数组：这张表里的行是**数据**，
--  别的迁移或人可能已经往里加过东西；直接覆盖会把那些改动静默抹掉。
--
--  用 `json_insert` 而不是字符串拼接：`produced_by` 是 canonical JSON 数组
--  （`[]` / `["x"]`），字符串拼接在遇到 `["a","b"]` 时也一样对，但它在遇到
--  **坏数据**时会静默产出一个畸形数组，而 json 函数会让整个迁移当场回滚。
--  两个 NOT EXISTS 是双保险（重复执行不叠加）：一个挡"已经追加过"，
--  一个挡"原来的值里本来就有 nmap@1"（003 的种子里没有，但数据是数据）。

UPDATE kind_registry
   SET produced_by = json_insert(produced_by, '$[#]', 'nmap@1')
 WHERE kind IN ('domain', 'ip', 'service', 'product')
   AND NOT EXISTS (SELECT 1 FROM json_each(produced_by) WHERE json_each.value = 'nmap@1')
   AND json_valid(produced_by);
