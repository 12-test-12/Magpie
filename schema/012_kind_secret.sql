--  012_kind_secret.sql —— 登记 `secret`：敏感串扫描（4.2）产出的那个 kind。
--
--  与 004–007 / 011 同一条纪律：**只增不改**（红线 R4）。已应用的迁移被改动
--  → 校验和不匹配 → `migrate()` 直接报错。所以这一份**只**往词表里加一行，
--  不碰任何既有列、既有表、既有 CHECK（011 那次重建 `inbox_items` 的代价是
--  一次性的，本步不需要第二遍）。
--
--  ---------------------------------------------------------------------------
--  一、为什么 `secret` 是一个 kind，而不是 `flow` 上的一条观测
--  ---------------------------------------------------------------------------
--  最省事的做法是在 `flow` 实体上挂一条 `secret_hint` 观测，像计划书 §4.4 的
--  分层图里那一格写的那样。这条路被否掉，理由是**身份**：
--
--      同一个 token 出现在三段会话里
--        → 挂在 flow 上：三条观测、三个不同的主体、三条互不相干的记录
--        → 落成 secret 实体：**一个**实体，`occurrence_count = 3`
--
--  "这个凭据泄漏到了几个地方"是这一步唯一要回答的问题（计划书 §3.5 流量镜头
--  那一行写的就是「有 token 泄漏吗」），而挂在 flow 上之后它**问不出来** ——
--  要答它就得去 grep 三条观测的值，而那三条的值在库里根本不存在（只有哈希）。
--  共享的东西必须外提为实体，这是计划书 §3.6 第 4 条。
--
--  ---------------------------------------------------------------------------
--  二、为什么镜头归属是 `traffic` 而不是 `assets`
--  ---------------------------------------------------------------------------
--  两个都说得通，所以把理由写下来（放行说明要求：要改就得先给理由）：
--
--    * 计划书 §3.5 的镜头表里，**流量**那一行的主语 kind 写的就是
--      `flow / secret`，典型问题写的是「有 token 泄漏吗」—— 这是**已冻结的
--      设计**，不是一次新判断；
--    * `secret` 与 `flow` 同源：两者的输入都是流量文本（HAR / 抓包 / curl
--      命令），一个从里面提炼"谁跟谁说了话"，另一个提炼"里面有没有凭据"；
--    * 归 `assets` 的唯一理由是"它是被泄漏的东西"，但 `assets` 那一行的主语
--      是 `domain / ip / cidr` —— 一台主机是**资产**，一个 token 不是：它没有
--      拓扑位置，也不参与"还有哪些没测"这个问题。
--
--  ⚠️  镜头只有 001 的 CHECK 里那六个，R4 不许改 001 —— 所以"流量镜头"就是
--  `traffic`，不是另起一个名字（`flow` 在 011 里已经走过一遍同一条路）。
--
--  ---------------------------------------------------------------------------
--  三、`produced_by` 是空的 —— 这不是漏填
--  ---------------------------------------------------------------------------
--  4.1 的 `flow` 在这里写 `["har@1","tshark@1"]`。`secret` 一个都不写，理由
--  是**它的产出者不是一个解析器**：敏感串扫描是一条独立的管线阶段
--  （`magpie/core/scan.py`），跑在解析**之后**、与选中的解析器**正交** ——
--  同一个 token 在一份 HAR 里，无论这份文件被 har 还是被 curl 认领，扫出来的
--  结果必须一模一样。把它挂到某个指纹上，就等于宣称"换个解析器就换一套扫描
--  结果"，而那是假的。
--
--  这条纪律的代价写在明处：`magpie kinds` 里这一行的"产出者"一栏是空的。
--  一个空的格子比一个编出来的指纹诚实 —— 后者会被
--  `verify_g3.py` 的 B 段（`produced_by` 必须在该来源自己的黄金夹具里真的
--  出现）当场抓住，因为没有任何一份黄金夹具里会出现 `secret` 实体：
--  扫描不是解析器，它的输出不进 `expected.json`（那些夹具是**逐字段合同**，
--  多一条记录就红）。所以这里是**结构上**空的，不是"忘了填"。
--
--  ---------------------------------------------------------------------------
--  四、夹具与身份规则（三件套的另一半）
--  ---------------------------------------------------------------------------
--  正文与 `fixtures/kinds/secret.json` 的 `identity_rule` **逐字一致**
--  （`test_every_registered_kind_has_all_three_parts` 断言这一点），并与
--  `base.KIND_REGISTRY` 的镜像逐行一致（`test_kind_registry_matches_the_python_
--  mirror` 断言那一半）。所以下面这一个字面量是**三处落点的共同来源**。
--
--  ⚠️  这段正文 893 个字，**手抄必错**。改它的时候跑
--  `py -3.13 _scratch/s42/write_012.py`（正文的唯一来源是
--  `_scratch/s42/rule_text.py`）与 `py -3.13 _scratch/s42/gen_secret_fixture.py`
--  （夹具从**应用迁移之后的库**里读那一行生成）—— 抄写错误从"可能发生"
